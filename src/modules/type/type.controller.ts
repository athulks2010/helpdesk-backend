import { TypeService } from './type.service'

export class TypeController {
  private service = new TypeService()

  all(query: any) {
    return this.service.findAll(query)
  }

  async single(query: any) {
    const item = await this.service.findById(query.id)
    return { ...(item?.toJSON?.() || item), message: 'Type fetched successfully' }
  }

  async create(body: any) {
    const item = await this.service.create(body)
    return { ...(item?.toJSON?.() || item), message: 'Type created successfully' }
  }

  async update(body: any) {
    const item = await this.service.update(body)
    return { ...(item?.toJSON?.() || item), message: 'Type updated successfully' }
  }

  async delete(query: any) {
    const item = await this.service.destroy(query.id)
    return { ...(item?.toJSON?.() || item), message: 'Type deleted successfully' }
  }

  async restore(body: any) {
    const item = await this.service.restore(body.id)
    return { ...(item?.toJSON?.() || item), message: 'Type restored successfully' }
  }
}
